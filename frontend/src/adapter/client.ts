// src/api/client.ts
import createClient from 'openapi-fetch'
import type { paths } from '../types/api' // Generated by openapi-typescript
import type { paths as AuthPaths } from '../types/auth-api'
import { getActivePinia } from 'pinia'
import { useAuthStore } from '@/stores/auth'

export const api = createClient<paths & AuthPaths>({
  baseUrl: '',
})

type Csrf = { token: string; headerName: string }
let csrf: Csrf | null = null
let pendingCsrf: Promise<Csrf> | null = null
let workspaceRequests = new AbortController()

export function cancelWorkspaceRequests(): void {
  workspaceRequests.abort()
  workspaceRequests = new AbortController()
}

export function clearCsrf(): void {
  csrf = null
  pendingCsrf = null
}

export async function refreshCsrf(): Promise<Csrf> {
  if (csrf) return csrf
  if (!pendingCsrf) {
    pendingCsrf = (async () => {
      const { data, error } = await api.GET('/api/auth/csrf')
      if (error || !data?.token || !data.headerName)
        throw new Error('The server could not verify this request. Please try again.')
      csrf = { token: data.token, headerName: data.headerName }
      return csrf
    })().finally(() => {
      pendingCsrf = null
    })
  }
  return pendingCsrf
}

api.use({
  async onRequest({ request }) {
    const workspaceSignal = workspaceRequests.signal
    if (!['GET', 'HEAD', 'OPTIONS'].includes(request.method)) {
      const token = await refreshCsrf()
      request.headers.set(token.headerName, token.token)
    }
    const path = new URL(request.url).pathname
    if (!path.startsWith('/api/auth/') && path !== '/api/whoami') {
      return new Request(request, {
        signal: AbortSignal.any([request.signal, workspaceSignal]),
      })
    }
    return request
  },
  async onResponse({ request, response }) {
    const path = new URL(request.url).pathname
    if ((path === '/api/auth/login' || path === '/api/auth/logout') && response.ok) clearCsrf()
    if (response.status === 401 && !path.startsWith('/api/auth/')) {
      clearCsrf()
      if (getActivePinia()) useAuthStore().expireSession()
    }
    if (response.status === 403) {
      const body = await response
        .clone()
        .json()
        .catch(() => null)
      if (body?.error?.code === 'csrf_invalid') {
        clearCsrf()
        if (getActivePinia()) await useAuthStore().refresh()
      }
    }
    return response
  },
})
